inline constexpr size_t Z1_PARAM_COUNT = sizeof(Z1_PARAMS) / sizeof(Z1_PARAMS[0]);

// Checked when the firmware is compiled: sorted by key, no key twice, every
// list parameter has its list and stays inside it.
constexpr bool z1ParamsAreValid() {
  for (size_t i = 0; i < Z1_PARAM_COUNT; ++i) {
    const ParamDef& p = Z1_PARAMS[i];
    if (i > 0 && Z1_PARAMS[i - 1].key >= p.key) return false;
    if (p.min > p.max) return false;
    if ((p.type == editableType::TextEnum) != (p.list != nullptr)) return false;
    if (p.list != nullptr && (p.min < 0 || p.max >= p.list->count)) return false;
  }
  return true;
}
static_assert(z1ParamsAreValid(), "Z1_PARAMS must be sorted by key, without duplicates, and each list parameter within its list");

// The index of a key in Z1_PARAMS, or -1. Usable at compile time as well.
constexpr int z1ParamIndex(int key) {
  int lo = 0, hi = (int)Z1_PARAM_COUNT - 1;
  while (lo <= hi) {
    int mid = (lo + hi) / 2;
    if (Z1_PARAMS[mid].key == key) return mid;
    if (Z1_PARAMS[mid].key < key) lo = mid + 1;
    else hi = mid - 1;
  }
  return -1;
}
