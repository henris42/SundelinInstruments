// z1_params.h - every parameter the editor knows, as one constant table.
//
// One line per parameter: key, name on the display (7 characters at most),
// lowest and highest value, start value, type, and for a parameter that is
// chosen from a list, the list.
//
// The key is the Korg Z1 parameter ID, with the ExID of the type-dependent
// blocks in the bits above it (see the Korg MIDI implementation, "The format
// of a program parameter ID"):
//        0 + id   program parameters
//   0x0800 + id   OSC1 type-dependent parameters        (O1 in Z1.cpp)
//   0x1000 + id   OSC2 type-dependent parameters        (O2)
//   0x1800 + id   effect 1                              (E1)
//   0x2000 + id   effect 2                              (E2)
//   0x2800 + id   master effect                         (EGL)
//   10000 and up, where it does not fall into one of the blocks above:
//                 settings of the Buddy itself, never sent to the Z1
//
// The table must stay sorted by key, without duplicates; the compiler checks
// that (see the static_assert at the end). The editor finds a parameter by
// binary search.
//
// This table replaced 784 hand-written "new EditableValue(...)" lines in
// Z1.cpp (November 2026). It was produced by running those lines and writing
// down what they built, so it is the same set of parameters, to the letter.
#pragma once
#include <cstddef>
#include <cstdint>

enum class editableType : uint8_t {
  Integer,
  Float,
  TextEnum,
  None
};

// The names to choose from, for a TextEnum parameter.
struct ParamList {
  const char* const* items;
  uint16_t count;
};

struct ParamDef {
  uint16_t key;
  const char* name;
  int16_t min, max, def;
  editableType type;
  const ParamList* list;    // nullptr unless type is TextEnum
};

